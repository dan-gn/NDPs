class PolicyNetwork(nn.Module):

    # ---------------------------------------------------------------------------------------
    # Initialisation
    # ---------------------------------------------------------------------------------------

    def __init__(self, graph:Graphnx, n_inputs, n_outputs, network_extra_thinking):
        super().__init__()
        
        self.graph = graph
        self.propagation_distance = self.graph.get_propagation_distance()
        self.network_extra_thinking = network_extra_thinking
        
        self.n_inputs, self.n_outputs = n_inputs, n_outputs
        self.n_nodes = graph.number_of_nodes()

        weights = torch.tensor(graph.get_weight_matrix(), dtype=torch.float32)
        adjacency_matrix = torch.tensor(graph.get_adjacency_matrix(), dtype=torch.bool)

        if self.n_nodes < n_inputs + n_outputs:
            temp_n_nodes = n_inputs + n_outputs

            temp_weights = torch.zeros((temp_n_nodes, temp_n_nodes), dtype=torch.float32)
            temp_weights[:self.n_nodes, :self.n_nodes] = weights

            temp_adjacency = torch.zeros((temp_n_nodes, temp_n_nodes), dtype=torch.float32)
            temp_adjacency[:self.n_nodes, :self.n_nodes] = adjacency_matrix

            self.n_nodes = temp_n_nodes
            weights = temp_weights
            adjacency_matrix = temp_adjacency


        self.register_buffer('weights', weights)
        self.register_buffer('adjacency_matrix', adjacency_matrix)
        self.reset_activations()

    def reset_activations(self):
        self.current_activations = None

    # ---------------------------------------------------------------------------------------
    # Forward function
    # ---------------------------------------------------------------------------------------

    def forward(self, x:torch.Tensor, steps:int=None):

        if steps is None:
            steps = max(1, self.propagation_distance + self.network_extra_thinking)

        if self.current_activations is None:
            self.current_activations= torch.zeros(1, self.n_nodes, dtype=torch.float32, device=x.device)
 
        activations = self.current_activations.clone()
        activations[:, :self.n_inputs] = x

        for _ in range(steps):
            output = activations @ self.weights
            post_activations = torch.tanh(output)
            post_activations[:, :self.n_inputs] = x
            activations = post_activations

        self.current_activations = post_activations

        return output[:, -self.n_outputs:]
                                         
                        
'''
---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
Artificial Neural Network created from a graph generated by an NDP that uses Neural Centric Hebbian Learning (NcHL)
---------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
'''

class NcHebbianLearningPolicyNetwork(PolicyNetwork):

    # ---------------------------------------------------------------------------------------
    # Initialisation
    # ---------------------------------------------------------------------------------------

    def __init__(self, graph:Graphnx, n_inputs:int, n_outputs:int, network_extra_thinking:int):
        super().__init__(graph, n_inputs, n_outputs, network_extra_thinking)

        self.reset_weights()

        if graph.state_dim < 5:
            raise ValueError('NcHL requires graph.state_dim >= 5.')

        # Check that the all nodes have a state
        if self.n_nodes > len(graph.nodes_states):
            self.nodes_states = np.zeros((self.n_nodes, graph.state_dim))
            self.nodes_states[:len(graph.nodes_states), :] = graph.nodes_states
        else:
            self.nodes_states = graph.nodes_states.copy()

        self.get_hebbian_matrix()

    def reset_weights(self):
        self.register_buffer('current_weights', self.weights.clone())
    
    # ---------------------------------------------------------------------------------------
    # Hebbian Learning functions
    # ---------------------------------------------------------------------------------------

    # Create Hebbian Matrix based on Neuron-centric Hebbian Learning (NcHL)
    def get_hebbian_matrix(self):
        hebbian_coeff = np.asarray(self.nodes_states)[:, :5]
        hebbian_coeff = torch.tensor(hebbian_coeff, dtype=torch.float32)
        hebbian_matrix = torch.empty((self.n_nodes, self.n_nodes, 5))

        # ETA = (etai + etaj)/2
        hebbian_matrix[:, :, 0] = (hebbian_coeff[:, None, 0] + hebbian_coeff[None, :, 0]) / 2
        
        # A = Ai
        hebbian_matrix[:, :, 1] = hebbian_coeff[:, None, 1]

        # B = Bj
        hebbian_matrix[:, :, 2] = hebbian_coeff[None, :, 2]

        # C = Ci*Cj and D = Di*Dj
        hebbian_matrix[:, :, 3:5] = hebbian_coeff[:, None, 3:5] * hebbian_coeff[None, :, 3:5]

        self.register_buffer('hebbian_matrix', hebbian_matrix)


    # Compute Hebbian delta
    def compute_hebbian_delta(self, pre:torch.Tensor, post:torch.Tensor):

        ETA, A, B, C, D = self.hebbian_matrix.unbind(dim=2)

        pre = pre.squeeze(0)
        post = post.squeeze(0)

        # Check __init__ for context
        # delta = (etai+etaj/2) * (Ai*pre + Bj*post + Ci*Cj*pre*post + Di*Dj)
        delta = ETA * (
            A * pre[:, None]
            + B * post[None, :]
            + C * pre[:, None] * post[None, :]
            + D
        )

        delta *= self.adjacency_matrix

        return delta

    def apply_hebbian_update(self, weights:torch.Tensor, delta:torch.Tensor):
        return torch.clamp(weights + delta, -1.0, 1.0)

    # ---------------------------------------------------------------------------------------
    # Forward function
    # ---------------------------------------------------------------------------------------

    def forward(self, x:torch.Tensor, steps:int=None):

        if steps is None:
            steps = max(1, self.propagation_distance + self.network_extra_thinking)

        if steps < 1:
            raise ValueError('The number of propagation steps must be at least 1.')


        if self.current_activations is None:
            self.current_activations= torch.zeros(1, self.n_nodes, dtype=torch.float32, device=x.device)

        activations = self.current_activations.clone()
        activations[:, :self.n_inputs] = x

        weights = self.current_weights
        total_delta = torch.zeros_like(weights)

        for _ in range(steps):
            pre_activations = activations

            output = activations @ weights
            post_activations = torch.tanh(output)

            post_activations[:, :self.n_inputs] = x

            total_delta += self.compute_hebbian_delta(pre_activations, post_activations)

            activations = post_activations

        mean_delta = total_delta / steps

        self.current_activations = post_activations
        self.current_weights = self.apply_hebbian_update(weights, mean_delta)

        return output[:, -self.n_outputs:]
                                         
                        





